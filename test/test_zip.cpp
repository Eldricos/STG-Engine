namespace {

std::string expectedLog() {
	std::string text;
	for (int i = 0; i < 120; i++)
		text += "Captain Picard to Enterprise, line " + std::to_string(i % 37) + ". ";
	return text;
}

std::string readAll(Common::SeekableReadStream &stream) {
	std::vector<byte> data = stream.readAll();
	return std::string(data.begin(), data.end());
}

} // End of anonymous namespace

TEST(crc32_vectors) {
	CHECK_EQ(Common::crc32((const byte *)"", 0), 0u);
	CHECK_EQ(Common::crc32((const byte *)"123456789", 9), 0xCBF43926u);
	// Running CRC over two halves equals the CRC of the whole.
	uint32 part = Common::crc32((const byte *)"12345", 5);
	CHECK_EQ(Common::crc32((const byte *)"6789", 4, part), 0xCBF43926u);
}

TEST(inflate_rejects_corruption) {
	// "abcabcabcabc" compressed by zlib (raw DEFLATE, fixed Huffman).
	const byte good[] = { 0x4b, 0x4c, 0x4a, 0x4e, 0x84, 0x21, 0x00 };
	byte out[12];
	CHECK(Common::inflateRaw(good, sizeof(good), out, sizeof(out)));
	CHECK_EQ(std::string((char *)out, 12), std::string("abcabcabcabc"));

	// Wrong expected size, truncated input, invalid block type.
	byte small[4];
	CHECK(!Common::inflateRaw(good, sizeof(good), small, sizeof(small)));
	CHECK(!Common::inflateRaw(good, 3, out, sizeof(out)));
	const byte badType[] = { 0x07 };
	CHECK(!Common::inflateRaw(badType, 1, out, sizeof(out)));
}

TEST(zip_archive_members) {
	Test::TempDir dir;
	dir.writeFile("TEST.DAT", std::vector<unsigned char>(Test::kTestZip, Test::kTestZip + Test::kTestZipSize));

	std::shared_ptr<Common::ZipArchive> zip = Common::ZipArchive::open(dir.node().getChild("TEST.DAT"));
	CHECK(zip != nullptr);
	if (!zip)
		return;

	// The directory entry is skipped; backslashes become slashes.
	CHECK_EQ(zip->getEntries().size(), (size_t)4);
	CHECK(zip->hasFile("data/log.TXT"));
	CHECK(zip->hasFile("Data\\Log.txt"));
	CHECK(!zip->hasFile("SUB/"));

	Common::File f;
	CHECK(f.open("readme.txt", *zip));
	CHECK_EQ(readAll(f), std::string("stored member\r\n"));
	CHECK(f.open("SHORT.TXT", *zip));
	CHECK_EQ(readAll(f), std::string("abcabcabcabc"));
	CHECK(f.open("DATA/LOG.TXT", *zip));
	CHECK_EQ(readAll(f), expectedLog());
	CHECK(f.open("RAW.BIN", *zip));
	CHECK_EQ(f.size(), (int64)300);

	Common::ArchiveMemberList members;
	CHECK_EQ(zip->listMatchingMembers(members, "*.txt"), 3);

	// Usable through SearchMan like any other archive.
	Common::SearchSet set;
	set.add("zip", zip);
	CHECK(f.open("short.txt", set));
}

TEST(zip_rejects_non_zip) {
	Test::TempDir dir;
	dir.writeFile("NOT.DAT", "this is not a zip file at all, just some text");
	CHECK(Common::ZipArchive::open(dir.node().getChild("NOT.DAT")) == nullptr);
}
